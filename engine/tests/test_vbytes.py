"""TBL with a one-register table, EXT, 128-bit vector loads and DUP by element (nx2/fastvec.py, HL_FASTVEC=1: a64_tbl1,
A64_EXT16, A64_EXT8, a64_vld16, a64_vdup), bit-exact with the text the kit writes for them, game-free.

(Ported from Longshot deb08f36f's tests/test_vbytes.py, tests/vbytes_test.c and tests/x86_test_host.h, MagicBeanDev/Longshot
#1576, Veix and HumanBean, GPL-3.0-or-later. HeyListen's: the passes run on the final instruction text, so each word is
checked with the kit's widened stores and with A64_NO_VSET=1's plain ones; the hot functions' path (hot_text) too; the
compiler is found as tests/test_vfpx_elem.py finds it; fewer random states by default.)

Guest words (TBL 8 and 16 bytes; EXT 16 bytes at every imm 0-15 and 8 bytes at every imm 0-7; LDR Q, LDP Q, post-index
LDR Q; DUP by element of every size; Vd apart, Vd = Vn, Vd = Vm, one register for all, registers above 15) go through
a64emit.translate and a64_lift.op_text twice: with fastvec installed and with A64_NO_VBYTES=1 A64_NO_VMOVES=1 (the kit's
text). The first must call the helper and keep no byte loop, the second must be the kit's. tests/vbytes_test.c runs both
from the same random Ctx (index bytes biased to the edges: 15, 16, 0x6f-0x90, 0xff) and compares all 32 vector registers
and the general ones. Built for -march=native, x86-64-v3, x86-64-v2 (SSSE3: the PSHUFB path) and x86-64 (SSE2 only: the
fallback); a build this CPU cannot run exits 3 at once and is reported as skipped.

    python -I -B tests/test_vbytes.py [--cc clang] [--cxx clang++] [--random 20000] [--time]

Skipped (exit 0) on a host that is not x86-64 or without a C/C++ compiler.
"""
import argparse
import os
import platform
import shutil
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "nx2"))
import test_fpx_sticky as fs  # noqa: E402  (its compiler search, flags and header generation)

SEED = 20261115
MARCHES = ("native", "x86-64-v3", "x86-64-v2", "x86-64")
REGS = ((0, 5, 1), (5, 5, 1), (1, 5, 1), (2, 2, 2), (3, 30, 17))   # (rd, rn, rm)


def tbl(q, rd, rn, rm):
    return 0x0E000000 | (q << 30) | (rm << 16) | (rn << 5) | rd


def ext(q, rd, rn, rm, imm):
    return 0x2E000000 | (q << 30) | (rm << 16) | (imm << 11) | (rn << 5) | rd


def shapes():
    out = []
    for q in (0, 1):
        for r in REGS:
            out.append(("TBL v%d.%s, {v%d.16b}, v%d.%s" % (r[0], "16b" if q else "8b", r[1], r[2], "16b" if q else "8b"),
                        tbl(q, *r), "a64_tbl1("))
    for q, n in ((1, 16), (0, 8)):
        for imm in range(n):
            for r in (REGS if imm in (0, 1, n // 2, n - 1) else REGS[:1]):
                out.append(("EXT v%d.%s, v%d, v%d, #%d" % (r[0], "16b" if q else "8b", r[1], r[2], imm),
                            ext(q, *r, imm), "A64_EXT%d(" % n))
    return out


def ldr_q(rt, rn, imm16):
    return 0x3DC00000 | ((imm16 // 16) << 10) | (rn << 5) | rt


def ldp_q(rt, rt2, rn, imm16):
    return 0xAD400000 | (((imm16 // 16) & 0x7f) << 15) | (rt2 << 10) | (rn << 5) | rt


def ldr_q_post(rt, rn, imm9):
    return 0x3CC00400 | ((imm9 & 0x1ff) << 12) | (rn << 5) | rt


def dup_elem(q, size, idx, rd, rn):
    imm5 = (idx << (size + 1)) | (1 << size)
    return 0x0E000400 | (q << 30) | (imm5 << 16) | (rn << 5) | rd


def move_shapes():
    out = [("LDR q3, [x1, #32]", ldr_q(3, 1, 32), "a64_vld16("), ("LDR q31, [x7]", ldr_q(31, 7, 0), "a64_vld16("),
           ("LDP q2, q9, [x1, #-64]", ldp_q(2, 9, 1, -64), "a64_vld16("),
           ("LDR q5, [x3], #48", ldr_q_post(5, 3, 48), "a64_vld16(")]
    for size, lanes in ((0, 16), (1, 8), (2, 4), (3, 2)):
        for q in ((1,) if size == 3 else (0, 1)):
            for idx in sorted({0, 1, lanes - 1}):
                for rd, rn in ((6, 2), (2, 2), (17, 30)):
                    out.append(("DUP v%d.%d%s, v%d[%d]" % (rd, (lanes if q else lanes // 2), "bhsd"[size], rn, idx),
                                dup_elem(q, size, idx, rd, rn), "a64_vdup("))
    return out


def lifted_cases(a64emit, a64_lift, fastvec, used):
    cases = shapes() + move_shapes()
    texts, fl = a64emit.translate([(0x1000 + 4 * i, w) for i, (_, w, _) in enumerate(cases)])
    if any(fl):
        raise SystemExit("vbytes: a64emit did not translate the guest words: %s" % fl)
    out = ["/* Generated by tests/test_vbytes.py: TBL (one register), EXT, Q loads and DUP, rewritten and as the kit writes them. */"]
    rows = []
    for form, env in (("widened", {}), ("plain stores", {"A64_NO_VSET": "1"})):
        os.environ.update(env)
        try:
            now = [a64_lift.op_text(t, used) for t in texts]
            os.environ["A64_NO_VBYTES"] = os.environ["A64_NO_VMOVES"] = "1"
            try:
                old = [a64_lift.op_text(t, used) for t in texts]
            finally:
                del os.environ["A64_NO_VBYTES"], os.environ["A64_NO_VMOVES"]
        finally:
            for k in env:
                del os.environ[k]
        for i, (n, o, (name, _, helper)) in enumerate(zip(now, old, cases)):
            if helper not in n or "for(int _i" in n:
                raise SystemExit("vbytes: %s (%s) was not rewritten: %s" % (name, form, n[:300]))
            if helper in o:
                raise SystemExit("vbytes: %s (%s) as the kit writes it already has the helper: %s" % (name, form, o[:300]))
            if getattr(n, "kit", None) != o:
                raise SystemExit("vbytes: %s (%s): the rewritten text does not carry the kit's (.kit), which hot functions use" % (name, form))
            if a64_lift.hot_text(o) != fastvec.fastvec_text(o) or helper not in a64_lift.hot_text(o):
                raise SystemExit("vbytes: %s (%s): a hot function's text is not rewritten after hot_text" % (name, form))
            k = len(rows)
            out.append("static void g_now%d(Ctx *__restrict c) { %s }" % (k, n))
            out.append("static void g_old%d(Ctx *__restrict c) { %s }" % (k, o))
            rows.append("%s, %s" % (name, form))
    out.append("static const struct { const char *name; void (*now)(Ctx *), (*old)(Ctx *); } CASES[] = {%s};"
               % ", ".join('{"%s", g_now%d, g_old%d}' % (r, i, i) for i, r in enumerate(rows)))
    return "\n".join(out) + "\n"


def generate(cxx, tmp, flags):
    dll = os.path.join(tmp, "a64emit.dll" if os.name == "nt" else "liba64emit.so")
    fs.build([cxx, "-std=c++20", "-O0", "-shared", "-Wno-everything", "-o", dll, os.path.join(fs.KIT, "lift", "a64emit.cpp")]
             + flags + ([] if os.name == "nt" else ["-fPIC"]), "a64emit")
    import build_emit
    build_emit.build = lambda force=False: dll
    import a64_lift
    import a64_rtgen
    import a64emit
    import fastvec   # (the passes under test: nx2/fastvec.py, around the kit's)
    fastvec.install()
    used = set()
    try:
        a64_rtgen.write(tmp)
        lifted = lifted_cases(a64emit, a64_lift, fastvec, used)
    finally:
        if a64emit._lib is not None:
            import _ctypes
            (_ctypes.FreeLibrary if os.name == "nt" else _ctypes.dlclose)(a64emit._lib._handle)
            a64emit._lib = None
    with open(os.path.join(tmp, "vbytes_lifted.h"), "w", newline="\n") as f:
        f.write(lifted)
    with open(os.path.join(tmp, "a64_fpx.h"), "w", newline="\n") as f:
        f.write(a64_lift.fpx_header(used))


def toolchain(a):
    """(cc, cxx, flags_of(tmp)) as tests/test_vfpx_elem.py finds them: the build's own host toolchain first"""
    if not os.environ.get("HOOKSHOT_MINGW") and os.name == "nt":   # (an llvm-mingw on PATH, as the tests are run here)
        w = shutil.which("clang++")
        if w and os.path.isfile(os.path.join(os.path.dirname(w), "x86_64-w64-mingw32-clang++.exe")):
            os.environ["HOOKSHOT_MINGW"] = os.path.dirname(os.path.dirname(w))
    if not a.cc and not a.cxx:
        try:
            tcc, tcxx = fs.toolchain.find("clang", host=True), fs.toolchain.find("clang++", host=True)
            if os.path.isfile(tcc) and os.path.isfile(tcxx):
                flags = fs.toolchain.native_target(host=True) + fs.toolchain.native_link(host=True)
                return tcc, tcxx, lambda tmp: flags
        except Exception:
            pass
    cc = fs.compiler(a.cc, "CC", ("clang", "gcc", "cc"), "clang")
    cxx = fs.compiler(a.cxx, "CXX", ("clang++", "g++", "c++"), "clang++")
    return cc, cxx, (lambda tmp: fs.target_flags(cc, tmp))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--cc")
    p.add_argument("--cxx")
    p.add_argument("--random", type=int, default=20000)
    p.add_argument("--time", action="store_true", help="also time each word at -O1 -march=native, now and as the kit writes it")
    a = p.parse_args()
    if platform.machine().lower() not in ("x86_64", "amd64"):
        print("vbytes: skipped (not an x86-64 host: %s)" % platform.machine())
        return
    for k in ("HL_FASTVEC", "A64_NO_VBYTES", "A64_NO_VMOVES", "A64_NO_VSET", "A64_HOT_FUNCS"):
        os.environ.pop(k, None)
    cc, cxx, flags_of = toolchain(a)
    if not cc or not cxx:
        print("vbytes: skipped (no C/C++ compiler)")
        return
    t0 = time.time()
    failed, ran = [], []
    with tempfile.TemporaryDirectory(prefix="heylisten-vbytes-") as tmp:
        generate(cxx, tmp, flags_of(tmp))
        for march in MARCHES:
            exe = os.path.join(tmp, "vbytes_test_%s.exe" % march)
            fs.build([cc] + flags_of(tmp) + ["-march=" + march] + fs.FLAGS +
                     ["-D_CRT_SECURE_NO_WARNINGS", "-I" + os.path.join(fs.KIT, "rt"), "-I" + tmp, "-I" + HERE,
                      os.path.join(HERE, "vbytes_test.c"), os.path.join(tmp, "a64_suyu.c"), "-o", exe],
                     "the driver at " + march)
            r = fs.run([exe, "random", str(a.random), str(SEED)], timeout=1800)
            print("%-10s %s" % (march, r.stdout.rstrip()))
            if r.returncode == 3:   # (tests/x86_test_host.h: this CPU lacks an extension of that -march)
                print("%-10s skipped (this CPU is not %s)" % (march, march))
                continue
            ran.append(march)
            if r.returncode:
                failed.append("%s (exit %d)" % (march, r.returncode))
        if a.time:
            exe = os.path.join(tmp, "vbytes_time.exe")
            fs.build([cc] + flags_of(tmp) + ["-march=native", "-ffp-contract=off", "-fno-strict-aliasing", "-O1",
                      "-D_CRT_SECURE_NO_WARNINGS", "-I" + os.path.join(fs.KIT, "rt"), "-I" + tmp, "-I" + HERE,
                      os.path.join(HERE, "vbytes_test.c"), os.path.join(tmp, "a64_suyu.c"), "-o", exe], "the timing driver")
            r = fs.run([exe, "time"], timeout=1800)
            print("timing at -O1 -march=native:\n" + r.stdout.rstrip())
    if not ran:
        print("vbytes: skipped (this CPU runs none of the builds)")
        return
    if failed:
        raise SystemExit("vbytes: FAIL (%s) in %.1f s" % (", ".join(failed), time.time() - t0))
    print("vbytes: pass in %.1f s" % (time.time() - t0))


if __name__ == "__main__":
    main()
